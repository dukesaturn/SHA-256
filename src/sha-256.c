/**
 * @brief Init Costants H and K in the `sha256` algorithm
 * 
 * @param H constants array
 * @param K constants array
 */
static void initConstants(uint32_t *H, uint32_t *K)
{
    memcpy(H, HBluePrint, H_LEN * 4);
    memcpy(K, KBluePrint, K_LEN * 4);
}

/**
 * @brief Sha-256 algorithm.
 *
 * @param msg input data
 * @param messageSize size of the input data
 * @param digest the result. It's an array of `uint32_t`, with length 8
 *
 * @return 1 if an error occurs,
 * 0 if everything is ok.
 *
 * @note Set `errno` to `ENOMEM` if there's an allocation issue
 *
 */
int sha256(const uint8_t *msg, size_t messageSize, uint32_t *digest)
{
    uint32_t H[H_LEN];
    uint32_t K[K_LEN];

    initConstants(H, K);

    /** +9 = 1 byte (0x80 padding bit) + 8 bytes (64-bit message length) */
    size_t nOfBlocks = (size_t)ceil((double)(messageSize + 9) / (double)BLOCK_SIZE_BYTES);
    size_t paddedSize = nOfBlocks * BLOCK_SIZE_BYTES;

    uint8_t *data = (uint8_t *)malloc(paddedSize);
    /** Set to zero to ensure clean data, and for the next padding operations */
    memset(data, 0, paddedSize);

    if (!data)
    {
        errno = ENOMEM;
        return 1;
    }

    memcpy(data, msg, messageSize);
    padding(data, messageSize, paddedSize);

    uint32_t words[EXPANDED_WORDS_LENGTH] = {0};

    for (size_t i = 0; i < nOfBlocks; i++)
    {
        /** 64 words of 32-bit: first 16 copied, remaining 48 generated */
        generateWords(words, data+(i*BLOCK_SIZE_BYTES));
        compressionRounds(H, K, words);
    }

    memcpy(digest, H, H_LEN * 4);

    free(data);
    return 0;
}

/**
 * @brief Convert the digest of Sha256 from uint32_t array in string - with length 64 (i.e. DGST_LENGTH)
 *
 * @param digest the digest
 * @param dest destination string
 */
void digestToString(const uint32_t *digest, char *dest)
{
    for (size_t i = 0; i < 8; i++)
    {
        sprintf(dest + i * 8, "%08x", digest[i]);
    }
}

